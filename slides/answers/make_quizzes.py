#!/usr/bin/env python3
"""Write the end-of-module quiz slides into each deck, and (with --answers)
the answer keys into slides/answers/. Run from the repo root.

The quiz section of a deck starts at QUIZ_MARK; re-running replaces it.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from quiz_data import MODULES  # noqa: E402

QUIZ_MARK = "<!-- quiz: generated by slides/answers/make_quizzes.py on the quiz-answers branch -->"
PER_SLIDE = 4
LETTERS = "ABCD"


def question_md(n, q):
    lines = [f"{n}. {q['q']}"]
    if q["opts"]:
        opts = " &nbsp;·&nbsp; ".join(f"**{L}** {o}" for L, o in zip(LETTERS, q["opts"]))
        lines.append(f'   <span class="opts">{opts}</span>')
    else:
        lines[0] += ' <span class="sa">*(short answer)*</span>'
    return "\n".join(lines)


def quiz_slides(questions):
    chunks = [questions[i:i + PER_SLIDE] for i in range(0, len(questions), PER_SLIDE)]
    out = [QUIZ_MARK]
    for s, chunk in enumerate(chunks):
        if s:
            out.append("\n---\n")
        out.append("\n<!-- _class: quiz -->\n")
        out.append(f"## Quiz ({s + 1}/{len(chunks)})\n")
        first = s * PER_SLIDE + 1
        out.append("\n".join(question_md(first + i, q) for i, q in enumerate(chunk)))
        if s == len(chunks) - 1:
            out.append("\n> Answer on paper first, then check yourself against the answer key "
                       "on the `quiz-answers` branch (`slides/answers/`).")
    return "\n".join(out) + "\n"


def write_deck(path, questions):
    with open(path) as f:
        text = f.read()
    if QUIZ_MARK in text:
        text = text[:text.index(QUIZ_MARK)].rstrip() + "\n"
        # drop the slide separator that preceded the old quiz
        if text.rstrip().endswith("---"):
            text = text.rstrip()[:-3].rstrip() + "\n"
    text = text.rstrip() + "\n\n---\n\n" + quiz_slides(questions)
    text = text.replace(QUIZ_MARK + "\n\n<!--", QUIZ_MARK + "\n<!--")
    with open(path, "w") as f:
        f.write(text)


def answer_md(deck, title, questions):
    out = [f"# Quiz answers: {title}", "",
           f"Answer key for the quiz at the end of [`{deck}`](../{deck}).", ""]
    for n, q in enumerate(questions, 1):
        out.append(f"## {n}. {q['q']}")
        out.append("")
        if q["opts"]:
            for L, o in zip(LETTERS, q["opts"]):
                mark = " ✔" if L == q["a"] else ""
                out.append(f"- **{L}** {o}{mark}")
            out.append("")
            out.append(f"**Answer: {q['a']}.** {q['why']}")
        else:
            out.append(f"**Answer:** {q['a']}")
            out.append("")
            out.append(q["why"])
        out.append("")
    return "\n".join(out)


def main():
    answers = "--answers" in sys.argv
    for deck, title, questions in MODULES:
        assert len(questions) == 8, deck
        for q in questions:
            if q["opts"]:
                assert len(q["opts"]) == 4 and q["a"] in LETTERS, q["q"]
        write_deck(os.path.join("slides", deck), questions)
        if answers:
            os.makedirs("slides/answers", exist_ok=True)
            with open(os.path.join("slides/answers", deck), "w") as f:
                f.write(answer_md(deck, title, questions))


if __name__ == "__main__":
    main()
