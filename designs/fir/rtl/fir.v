// fir.v -- 16-tap low-pass FIR filter, one multiply-accumulate (MAC) unit.
//
//            15
//     y[n] = SUM  h[k] * x[n-k]
//            k=0
//
// Number formats (see docs/fixed-point.md):
//   x, y : signed Q1.15   (16 bits, range [-1, 1))
//   h    : signed Q1.15   (designed by python/dsp_coeffs.py)
//   acc  : signed Q6.30   (16x16 products, plus 4 guard bits for 16 additions)
//
// Architecture: instead of 16 multipliers working in parallel (fast, big), a
// single multiplier is time-shared over the 16 taps (slow, small). A new
// sample is accepted every TAPS+1 = 17 clock cycles, so at 100 MHz this
// filter handles sample rates up to ~5.8 MHz -- plenty for audio. Trading
// throughput for area like this is one of the central decisions in DSP
// hardware; the IIR example (designs/iir) shows the fully parallel style.
//
// Handshake: present `in_sample` with `in_valid` while `in_ready` is high.
// `out_valid` pulses for one cycle when `out_sample` holds the new result.

`timescale 1ns/1ps
`default_nettype none

module fir #(
    parameter W = 16          // sample width (Q1.15 when 16)
) (
    input  wire                clk,
    input  wire                rst_n,
    input  wire                in_valid,
    output wire                in_ready,
    input  wire signed [W-1:0] in_sample,
    output reg                 out_valid,
    output reg  signed [W-1:0] out_sample
);

    localparam TAPS = 16;
    localparam CW   = 16;               // coefficient width
    localparam FRAC = 15;               // coefficient fractional bits (Q1.15)
    localparam AW   = W + CW + 4;       // accumulator: product + log2(TAPS) guard bits
    localparam IW   = 4;                // tap index width
    localparam [IW-1:0] K_LAST = IW'(TAPS - 1);

    // Coefficient ROM. Generated by python/dsp_coeffs.py: windowed-sinc
    // low-pass, cutoff 0.1*fs, Hamming window, sum = 32768 (DC gain 1.0).
    function signed [CW-1:0] coef;
        input [IW-1:0] k;
        begin
            case (k)
                 0: coef =   -114;
                 1: coef =   -159;
                 2: coef =   -139;
                 3: coef =    291;
                 4: coef =   1450;
                 5: coef =   3284;
                 6: coef =   5246;
                 7: coef =   6525;
                 8: coef =   6525;
                 9: coef =   5246;
                10: coef =   3284;
                11: coef =   1450;
                12: coef =    291;
                13: coef =   -139;
                14: coef =   -159;
                15: coef =   -114;
                default: coef = 0;
            endcase
        end
    endfunction

    // Delay line: delay[k*W +: W] holds x[n-k]
    reg  [TAPS*W-1:0]   delay;
    reg                 busy;
    reg  [IW-1:0]       k;
    reg  signed [AW-1:0] acc;

    assign in_ready = !busy;

    // The one multiplier: tap k times sample x[n-k]
    wire signed [W-1:0]    x_k  = delay[k*W +: W];
    wire signed [CW-1:0]   h_k  = coef(k);
    wire signed [W+CW-1:0] prod = x_k * h_k;
    wire signed [AW-1:0]   acc_next = acc + {{(AW-W-CW){prod[W+CW-1]}}, prod};  // sign-extend

    // Round to nearest (add half an LSB) then drop FRAC bits, then saturate
    // to the W-bit output range instead of wrapping around.
    wire signed [AW-1:0] rounded = (acc_next + (1 <<< (FRAC - 1))) >>> FRAC;
    localparam signed [AW-1:0] YMAX =  (1 <<< (W - 1)) - 1;
    localparam signed [AW-1:0] YMIN = -(1 <<< (W - 1));
    wire signed [W-1:0] y_sat = (rounded > YMAX) ? YMAX[W-1:0] :
                                (rounded < YMIN) ? YMIN[W-1:0] :
                                                   rounded[W-1:0];

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            delay      <= {TAPS*W{1'b0}};
            busy       <= 1'b0;
            k          <= {IW{1'b0}};
            acc        <= {AW{1'b0}};
            out_valid  <= 1'b0;
            out_sample <= {W{1'b0}};
        end else begin
            out_valid <= 1'b0;
            if (!busy) begin
                if (in_valid) begin
                    // Shift the new sample into the delay line, start a MAC run
                    delay <= {delay[(TAPS-1)*W-1:0], in_sample};
                    busy  <= 1'b1;
                    k     <= {IW{1'b0}};
                    acc   <= {AW{1'b0}};
                end
            end else begin
                acc <= acc_next;
                k   <= k + 1'b1;
                if (k == K_LAST) begin
                    busy       <= 1'b0;
                    out_valid  <= 1'b1;
                    out_sample <= y_sat;
                end
            end
        end
    end

endmodule

`default_nettype wire
