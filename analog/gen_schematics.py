#!/usr/bin/env python3
"""gen_schematics.py -- write the Xschem schematics in analog/sch/.

The schematics are ordinary Xschem files: open them with

    cd analog && xschem --rcfile xschemrc sch/dac_r2r8.sch

They are generated by this script (rather than drawn by hand) so that the
same code can draw a 3-bit flash ADC you can read and an 8-bit one you can
simulate, and so that every value is easy to change in one place:

    python3 analog/gen_schematics.py      # rewrites analog/sch/*.sch, *.sym

Only symbols from Xschem's standard `devices/` library are used, plus one
custom comparator symbol written below.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SCH = os.path.join(HERE, "sch")

VDD = 1.8            # sky130 core supply; also the DAC/ADC reference voltage
R_UNIT = "10k"       # R-2R ladder: R
R_TWO = "20k"        #              2R
R_LADDER = 1000      # flash ADC reference ladder: one LSB step (ohms)
CMP_GAIN = "1e5"     # comparator gain: 1/gain = 10 uV << 1 LSB (7 mV at 8 bits)

HEADER = "v {xschem version=3.4.4 file_version=1.2}\nG {}\nK {}\nV {}\nS {}\nE {}\n"


class Sheet:
    """A tiny writer for Xschem .sch files (components, wires, labels, text)."""

    def __init__(self):
        self.lines = []
        self.count = {}

    def _id(self, prefix):
        self.count[prefix] = self.count.get(prefix, 0) + 1
        return f"{prefix}{self.count[prefix]}"

    def comp(self, sym, x, y, rot=0, flip=0, **attrs):
        body = " ".join(f"{k}={v}" for k, v in attrs.items())
        self.lines.append(f"C {{{sym}}} {x} {y} {rot} {flip} {{{body}}}")

    def wire(self, *pts):
        for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
            self.lines.append(f"N {x1} {y1} {x2} {y2} {{}}")

    def label(self, x, y, name, rot=0, flip=0):
        self.comp("devices/lab_pin.sym", x, y, rot, flip, name=self._id("l"), lab=name)

    def gnd(self, x, y):
        self.comp("devices/gnd.sym", x, y, name=self._id("g"), lab="GND")

    def ipin(self, x, y, name, rot=0):
        self.comp("devices/ipin.sym", x, y, rot, name=self._id("p"), lab=name)

    def opin(self, x, y, name, rot=0):
        self.comp("devices/opin.sym", x, y, rot, name=self._id("p"), lab=name)

    def text(self, x, y, s, size=0.4):
        s = s.replace("{", "\\{").replace("}", "\\}")
        self.lines.append(f"T {{{s}}} {x} {y} 0 0 {size} {size} {{}}")

    def res_h(self, x, y, name, value):
        """Horizontal resistor centred at (x, y): pins at x-30 and x+30."""
        self.comp("devices/res.sym", x, y, 1, name=name, value=value, m=1)

    def res_v(self, x, y, name, value):
        """Vertical resistor centred at (x, y): pins at y-30 and y+30."""
        self.comp("devices/res.sym", x, y, 0, name=name, value=value, m=1)

    def cap_v(self, x, y, name, value):
        self.comp("devices/capa.sym", x, y, 0, name=name, value=value, m=1)

    def buffer(self, x, y, name):
        """Ideal unity-gain buffer (a VCVS) at (x, y).

        Pins: in (x-40, y-20), out (x, y-30); the minus input and minus
        output go to ground here."""
        self.comp("devices/vcvs.sym", x, y, name=name, value=1)
        self.gnd(x, y + 30)
        self.wire((x - 40, y + 20), (x - 40, y + 40))
        self.gnd(x - 40, y + 40)

    def save(self, path):
        with open(path, "w") as f:
            f.write(HEADER + "\n".join(self.lines) + "\n")
        print("wrote", os.path.relpath(path))


# ---------------------------------------------------------------------------
# Comparator symbol: an ideal (behavioural) comparator, out = VDD when inp > inn
# ---------------------------------------------------------------------------
COMPARATOR_SYM = r"""v {xschem version=3.4.4 file_version=1.2}
G {}
K {type=comparator
format="@name @@out 0 V = @vhigh * (0.5 + 0.5 * tanh( @gain * (V( @@inp ) - V( @@inn ))))"
template="name=B1 vhigh=1.8 gain=1e5"}
V {}
S {}
E {}
L 4 -20 -20 -20 20 {}
L 4 -20 -20 20 0 {}
L 4 -20 20 20 0 {}
L 4 -40 -10 -20 -10 {}
L 4 -40 10 -20 10 {}
L 4 20 0 40 0 {}
L 4 -16 -10 -10 -10 {}
L 4 -13 -13 -13 -7 {}
L 4 -16 10 -10 10 {}
B 5 -42.5 -12.5 -37.5 -7.5 {name=inp dir=in}
B 5 -42.5 7.5 -37.5 12.5 {name=inn dir=in}
B 5 37.5 -2.5 42.5 2.5 {name=out dir=out}
T {@name} 0 -32 0 0 0.2 0.2 {}
"""


def dac_r2r(bits=8):
    """N-bit R-2R ladder DAC, unity-gain buffer and 2-pole RC reconstruction filter."""
    s = Sheet()
    pitch = 160
    x = [200 + pitch * i for i in range(bits)]
    s.text(80, -330, f"{bits}-bit R-2R ladder DAC + reconstruction filter", 0.7)
    s.text(80, -270, f"vdac = VREF * code / {2 ** bits}   (bit inputs swing 0 .. VREF = {VDD} V)", 0.4)
    s.text(80, -235, f"R = {R_UNIT}, 2R = {R_TWO}.  Output impedance of the ladder is always R.", 0.4)

    # LSB-end termination: 2R to ground
    s.res_h(x[0] - 80, 0, "Rterm", R_TWO)
    s.wire((x[0] - 50, 0), (x[0], 0))
    s.wire((x[0] - 110, 0), (x[0] - 110, 30))
    s.gnd(x[0] - 110, 30)

    for i in range(bits):
        # the ladder node, its 2R leg down to the bit input
        s.label(x[i], 0, f"n{i}", flip=0)
        s.wire((x[i], 0), (x[i], 70))
        s.res_v(x[i], 100, f"R2_{i}", R_TWO)
        s.wire((x[i], 130), (x[i], 160))
        s.ipin(x[i], 160, f"b{i}", rot=3)
        if i < bits - 1:          # series R to the next node
            s.res_h(x[i] + 80, 0, f"R1_{i}", R_UNIT)
            s.wire((x[i], 0), (x[i] + 50, 0))
            s.wire((x[i] + 110, 0), (x[i + 1], 0))

    s.text(x[0] - 40, 200, "LSB", 0.4)
    s.text(x[-1] - 40, 200, "MSB", 0.4)

    # buffer the ladder output
    xm = x[-1]
    s.wire((xm, 0), (xm + 100, 0))
    s.buffer(xm + 140, 20, "Ebuf")
    s.wire((xm + 140, -10), (xm + 140, -60), (xm + 180, -60))
    s.wire((xm + 180, -60), (xm + 180, -100))
    s.opin(xm + 180, -100, "vdac", rot=3)
    s.wire((xm + 180, -60), (xm + 250, -60))

    # 2-pole reconstruction filter: R-C, buffer, R-C (fc = 7.2 kHz per pole)
    xf = xm + 280
    s.res_h(xf, -60, "Rf1", "10k")
    s.wire((xf + 30, -60), (xf + 70, -60))
    s.cap_v(xf + 70, -30, "Cf1", "2.2n")
    s.gnd(xf + 70, 0)
    s.label(xf + 70, -60, "f1")
    s.wire((xf + 70, -60), (xf + 130, -60))
    s.buffer(xf + 170, -40, "Ef")
    s.wire((xf + 170, -70), (xf + 170, -100), (xf + 210, -100))
    s.res_h(xf + 240, -100, "Rf2", "10k")
    s.wire((xf + 270, -100), (xf + 310, -100))
    s.cap_v(xf + 310, -70, "Cf2", "2.2n")
    s.gnd(xf + 310, -40)
    s.wire((xf + 310, -100), (xf + 370, -100))
    s.opin(xf + 370, -100, "vout")
    s.text(xf - 30, -200, "reconstruction filter", 0.4)
    s.text(xf - 30, -170, "2 x RC, fc = 7.2 kHz each", 0.3)
    s.save(os.path.join(SCH, f"dac_r2r{bits}.sch"))


def adc_flash(bits):
    """N-bit flash ADC: sample-and-hold, 2^N-1 comparators, thermometer encoder."""
    s = Sheet()
    m = 2 ** bits - 1            # number of comparators
    pitch = 80
    y_top = 200

    def y_tap(k):                # tap k = 1 (lowest threshold) .. m (highest)
        return y_top + (m - k + 1) * pitch

    s.text(-40, -150, f"{bits}-bit flash ADC ({m} comparators)", 0.7)
    s.text(-40, -90, "code = number of comparators that see vin above their tap", 0.4)
    s.text(-40, -55, f"thresholds at (k - 1/2) LSB, LSB = VREF / {2 ** bits}", 0.4)

    # sample-and-hold: switch closes while clk is high, C holds the value
    s.ipin(0, 0, "vin")
    s.wire((0, 0), (140, 0), (140, 10))
    s.comp("devices/switch_ngspice.sym", 140, 40, name="Ssh", model="SH_SW")
    s.ipin(40, 40, "clk")
    s.wire((40, 40), (100, 40))
    s.wire((100, 60), (100, 80))
    s.gnd(100, 80)
    s.wire((140, 70), (140, 100))
    s.label(140, 100, "vh", flip=0)
    s.wire((140, 100), (220, 100))
    s.cap_v(140, 130, "Chold", "1p")
    s.gnd(140, 160)
    s.buffer(260, 120, "Esh")
    s.wire((260, 90), (260, 60), (300, 60))
    s.label(300, 60, "vs", flip=1)
    s.text(0, 190, "sample & hold", 0.4)
    s.comp("devices/code_shown.sym", 0, 260, name="models", only_toplevel="false",
           value='".model SH_SW SW(vt=0.9 vh=0.1 ron=10 roff=1e12)"')

    # reference ladder: 1.5R at the top, R between taps, 0.5R at the bottom
    xl = 500
    s.ipin(420, y_top, "vref")
    s.wire((420, y_top), (xl, y_top))
    s.res_v(xl, y_top + 40, "Rtop", f"{1.5 * R_LADDER:g}")
    s.wire((xl, y_top), (xl, y_top + 10))
    s.wire((xl, y_top + 70), (xl, y_tap(m)))
    for k in range(m - 1, 0, -1):
        yc = y_tap(k) - pitch // 2
        s.res_v(xl, yc, f"R{k}", f"{R_LADDER:g}")
        s.wire((xl, y_tap(k + 1)), (xl, yc - 30))
        s.wire((xl, yc + 30), (xl, y_tap(k)))
    s.res_v(xl, y_tap(1) + 40, "Rbot", f"{0.5 * R_LADDER:g}")
    s.wire((xl, y_tap(1)), (xl, y_tap(1) + 10))
    s.wire((xl, y_tap(1) + 70), (xl, y_tap(1) + 80))
    s.gnd(xl, y_tap(1) + 80)

    # one comparator per tap
    for k in range(1, m + 1):
        y = y_tap(k)
        s.label(xl, y, f"r{k}", flip=1)
        s.wire((xl, y), (560, y))
        s.label(560, y - 20, "vs")
        s.comp("comparator.sym", 600, y - 10, name=f"Bc{k}", vhigh=VDD, gain=CMP_GAIN)
        s.wire((640, y - 10), (700, y - 10))
        s.label(700, y - 10, f"t{k}", flip=1)

    # encoder: count the comparators that are high (thermometer -> binary)
    xe = 900
    ye = y_top + 40
    terms = "+".join(f"u(V(t{k})-{VDD / 2:g})" for k in range(1, m + 1))
    s.comp("devices/bsource.sym", xe, ye + 30, name="Bcount", VAR="V",
           FUNC=f'"{terms}"')
    s.gnd(xe, ye + 60)
    s.wire((xe, ye), (xe, ye - 20), (xe + 80, ye - 20))
    s.opin(xe + 80, ye - 20, "code")
    s.text(xe + 40, ye - 110, "ones counter: code = sum of t1..t%d\n(1 V per LSB, an analog probe of the output code)" % m, 0.3)

    # output bits from the count
    for i in range(bits):
        xb = xe + 40 + 320 * i
        yb = ye + 260
        f = (f"{VDD:g}*(floor((V(code)+0.25)/{2 ** i})"
             f"-2*floor((V(code)+0.25)/{2 ** (i + 1)}))")
        s.comp("devices/bsource.sym", xb, yb, name=f"Bd{i}", VAR="V", FUNC=f'"{f}"')
        s.gnd(xb, yb + 30)
        s.wire((xb, yb - 30), (xb, yb - 60))
        s.opin(xb, yb - 60, f"d{i}", rot=3)
    s.save(os.path.join(SCH, f"adc_flash{bits}.sch"))


def main():
    os.makedirs(SCH, exist_ok=True)
    with open(os.path.join(SCH, "comparator.sym"), "w") as f:
        f.write(COMPARATOR_SYM)
    print("wrote", os.path.relpath(os.path.join(SCH, "comparator.sym")))
    dac_r2r(8)
    adc_flash(3)
    adc_flash(8)


if __name__ == "__main__":
    main()
