#!/usr/bin/env python3
"""analog.py -- simulate the ADC and DAC, and run the full signal chain.

    python3 analog/analog.py netlist   # Xschem schematics -> build/*.spice, *.lib
    python3 analog/analog.py dac       # 8-bit R-2R DAC: all 256 codes, DNL/INL
    python3 analog/analog.py adc       # 3-bit flash ADC: ramp test, every code checked
    python3 analog/analog.py chain     # sine -> 8-bit ADC -> fir.v -> DAC -> filter
    python3 analog/analog.py check     # all of the above, exit 1 on any FAIL
    python3 analog/analog.py plot      # check, then write the figures to docs/images/

Every test prints PASS or FAIL, like the digital testbenches. Needs ngspice,
xschem, iverilog and numpy (matplotlib for `plot`).
"""
import os
import re
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
BUILD = os.path.join(HERE, "build")
IMAGES = os.path.join(REPO, "docs", "images")

VREF = 1.8
SCHEMATICS = ["dac_r2r8", "adc_flash3", "adc_flash8"]

# Signal chain: what a microphone or sensor might deliver to the chip
FS = 48_000                 # sample rate (Hz)
F_SIG, A_SIG = 1_000, 0.50  # wanted tone (Hz, V peak)
F_INT, A_INT = 15_000, 0.15  # interferer the FIR should remove
N_CHAIN = 288               # samples = 6 ms = 6 periods of the 1 kHz tone

results = []


def report(name, ok, detail):
    results.append(ok)
    print(f"{'PASS' if ok else 'FAIL'}: {name}: {detail}")


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, cwd=HERE, stdin=subprocess.DEVNULL, **kw)


# ---------------------------------------------------------------------------
# Xschem -> ngspice
# ---------------------------------------------------------------------------
def netlist():
    """Netlist every schematic with Xschem and turn it into a .subckt library."""
    os.makedirs(BUILD, exist_ok=True)
    for name in SCHEMATICS:
        # absolute paths: xschem resolves relative ones against $PWD, not the cwd
        run(["xschem", "--rcfile", os.path.join(HERE, "xschemrc"), "-n", "-s", "-q", "-x",
             "--netlist_path", BUILD, os.path.join(HERE, "sch", f"{name}.sch")],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        src = open(os.path.join(BUILD, f"{name}.spice")).read()
        # Xschem writes the top level as a commented-out subckt; make it real
        lib = src.replace("**.subckt", ".subckt").replace("**.ends", ".ends")
        lib = re.sub(r"^\.end\s*$", "", lib, flags=re.M)
        with open(os.path.join(BUILD, f"{name}.lib"), "w") as f:
            f.write(lib)
    print("netlisted:", ", ".join(SCHEMATICS))


def ngspice(name, body, vectors, tstop, tstep):
    """Run a transient in ngspice; return (t, {vector: samples}) on a uniform grid."""
    dat = os.path.join(BUILD, f"{name}.dat")
    cir = f"""* {name} -- generated by analog/analog.py
{body}
.options savecurrents=0
.control
set wr_singlescale
set wr_vecnames
option numdgt=7
tran {tstep} {tstop} 0 {tstep}
linearize {' '.join(vectors)}
wrdata {dat} {' '.join(vectors)}
quit
.endc
.end
"""
    path = os.path.join(BUILD, f"{name}.cir")
    with open(path, "w") as f:
        f.write(cir)
    log = run(["ngspice", "-b", path], capture_output=True, text=True)
    if not os.path.exists(dat):
        sys.exit(f"ngspice wrote no data for {name}:\n{log.stdout[-2000:]}\n{log.stderr[-2000:]}")
    data = np.loadtxt(dat, skiprows=1)
    return data[:, 0], {v: data[:, i + 1] for i, v in enumerate(vectors)}


def bit_sources(codes, period, bits=8, edge=10e-9):
    """PWL voltage sources that drive bits b0..b7 with one code per period."""
    lines = []
    for b in range(bits):
        pts, level = [], None
        for n, c in enumerate(codes):
            v = VREF if (int(c) >> b) & 1 else 0.0
            t = n * period
            if level is None:
                pts.append((0.0, v))
            elif v != level:
                pts += [(t, level), (t + edge, v)]
            level = v
        pts.append((len(codes) * period, level))
        pwl = " ".join(f"{t:.9g} {v:g}" for t, v in pts)
        lines.append(f"Vb{b} b{b} 0 PWL({pwl})")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# DAC: every code, DNL and INL
# ---------------------------------------------------------------------------
def dac_sweep(lib="dac_r2r8.lib", name="dac_tb"):
    period = 10e-6
    codes = np.arange(256)
    body = f""".include {os.path.join(BUILD, lib)}
{bit_sources(codes, period)}
X1 b0 b1 b2 b3 b4 b5 b6 b7 vdac vout dac_r2r8
"""
    t, v = ngspice(name, body, ["v(vdac)"], 256 * period, 0.5e-6)
    idx = np.searchsorted(t, (codes + 0.5) * period)   # middle of each step
    return v["v(vdac)"][idx]


def linearity(vout):
    lsb = (vout[-1] - vout[0]) / 255            # end-point LSB
    dnl = np.diff(vout) / lsb - 1
    inl = (vout - vout[0]) / lsb - np.arange(256)
    return dnl, inl


def mismatched_lib(sigma=0.01, seed=7):
    """Copy of the DAC with every ladder resistor off by a random N(0, sigma)."""
    rng = np.random.default_rng(seed)
    src = open(os.path.join(BUILD, "dac_r2r8.lib")).read()

    def perturb(m):
        val = float(m.group(2).rstrip("k")) * 1e3
        return f"{m.group(1)} {val * (1 + sigma * rng.standard_normal()):.6g}"
    out = re.sub(r"^(R(?:term|1_\d|2_\d) \S+ \S+) (\d+k)", perturb, src, flags=re.M)
    with open(os.path.join(BUILD, "dac_r2r8_mc.lib"), "w") as f:
        f.write(out)
    return "dac_r2r8_mc.lib"


def dac():
    v = dac_sweep()
    dnl, inl = linearity(v)
    ideal = VREF * np.arange(256) / 256
    err = np.max(np.abs(v - ideal)) / (VREF / 256)
    report("dac", err < 0.01 and np.max(np.abs(dnl)) < 0.01,
           f"256 codes, vdac = VREF*code/256 within {err:.4f} LSB, "
           f"max |DNL| {np.max(np.abs(dnl)):.4f} LSB")
    vm = dac_sweep(mismatched_lib(), "dac_mc_tb")
    dnl_m, inl_m = linearity(vm)
    worst = int(np.argmax(np.abs(dnl_m)))
    print(f"      with 1% resistor mismatch: max |DNL| {np.max(np.abs(dnl_m)):.2f} LSB "
          f"(code {worst} -> {worst + 1}), max |INL| {np.max(np.abs(inl_m)):.2f} LSB")
    return dict(v=v, dnl=dnl, inl=inl, vm=vm, dnl_m=dnl_m, inl_m=inl_m)


# ---------------------------------------------------------------------------
# ADC: slow ramp through the 3-bit flash ADC
# ---------------------------------------------------------------------------
def clock(fs, high=2e-6):
    return f"Vclk clk 0 PULSE(0 {VREF} 0 10n 10n {high} {1 / fs:.9g})"


def sample_codes(t, code, fs, n):
    """Read the ADC output late in each hold phase, once per sample."""
    idx = np.searchsorted(t, (np.arange(n) + 0.9) / fs)
    return np.rint(code[idx]).astype(int)


def adc():
    fs, n = 100_000, 200
    tstop = n / fs
    body = f""".include {os.path.join(BUILD, 'adc_flash3.lib')}
Vref vref 0 {VREF}
Vin vin 0 PWL(0 -0.1 {tstop} {VREF + 0.1})
{clock(fs)}
X1 vin clk vref code d0 d1 d2 adc_flash3
"""
    vecs = ["v(vin)", "v(code)", "v(d0)", "v(d1)", "v(d2)", "v(x1.vs)"]
    t, v = ngspice("adc3_tb", body, vecs, tstop, 0.1e-6)
    code = sample_codes(t, v["v(code)"], fs, n)
    vs = v["v(x1.vs)"][np.searchsorted(t, (np.arange(n) + 0.9) / fs)]
    lsb = VREF / 8
    expect = np.clip(np.floor(vs / lsb + 0.5), 0, 7).astype(int)
    near = np.abs(vs / lsb - np.round(vs / lsb - 0.5) - 0.5) < 0.01   # on a threshold
    bad = np.sum((code != expect) & ~near)
    bits = sum(((code >> i) & 1) << i for i in range(3))
    idx = np.searchsorted(t, (np.arange(n) + 0.9) / fs)
    dbits = sum((v[f"v(d{i})"][idx] > VREF / 2).astype(int) << i for i in range(3))
    ok = bad == 0 and set(code) == set(range(8)) and np.all(np.diff(code) >= 0) \
        and np.array_equal(dbits, bits)
    report("adc", ok, f"3-bit flash, {n} samples on a ramp: {bad} wrong codes, "
           f"codes seen {sorted(int(x) for x in set(code))}, monotonic, bits d2..d0 match")
    return dict(t=t, v=v, vs=vs, code=code, fs=fs)


# ---------------------------------------------------------------------------
# The chain: analog in -> 8-bit ADC -> fir.v (Verilog!) -> 8-bit DAC -> analog out
# ---------------------------------------------------------------------------
def tone_amplitude(x, f, fs):
    """Amplitude of the tone at f in x (x covers a whole number of periods)."""
    n = np.arange(len(x))
    return 2 * abs(np.sum((x - np.mean(x)) * np.exp(-2j * np.pi * f * n / fs))) / len(x)


def chain():
    tstop = N_CHAIN / FS
    body = f""".include {os.path.join(BUILD, 'adc_flash8.lib')}
Vref vref 0 {VREF}
Vin vin 0 SIN({VREF / 2} {A_SIG} {F_SIG})
Vint vin2 vin SIN(0 {A_INT} {F_INT})
{clock(FS)}
X1 vin2 clk vref code d0 d1 d2 d3 d4 d5 d6 d7 adc_flash8
"""
    t, v = ngspice("chain_adc", body, ["v(vin2)", "v(code)"], tstop, 0.2e-6)
    codes = sample_codes(t, v["v(code)"], FS, N_CHAIN)

    # ADC code (offset binary, 0..255) -> Q1.15 two's complement for the FIR
    q15 = (codes - 128) << 8
    with open(os.path.join(BUILD, "adc_q15.hex"), "w") as f:
        f.writelines(f"{x & 0xFFFF:04x}\n" for x in q15)
    run(["iverilog", "-g2012", "-o", "build/chain_sim", "tb/fir_chain_tb.v",
         os.path.join(REPO, "designs", "fir", "rtl", "fir.v")])
    run(["vvp", "-n", "build/chain_sim", "+in=build/adc_q15.hex",
         "+out=build/fir_out.txt", f"+n={N_CHAIN}"])
    y = np.loadtxt(os.path.join(BUILD, "fir_out.txt"), dtype=int)

    # Q1.15 -> 8-bit DAC code: round to the top 8 bits, back to offset binary
    dac_codes = np.clip(((y + 128) >> 8) + 128, 0, 255)
    body = f""".include {os.path.join(BUILD, 'dac_r2r8.lib')}
{bit_sources(dac_codes, 1 / FS)}
X1 b0 b1 b2 b3 b4 b5 b6 b7 vdac vout dac_r2r8
"""
    td, vd = ngspice("chain_dac", body, ["v(vdac)", "v(vout)"], tstop, 0.2e-6)

    # Measure both tones on the last 4 ms (4 whole periods of 1 kHz, 60 of 15 kHz),
    # after the FIR and the reconstruction filter have settled
    sl = slice(N_CHAIN - 192, N_CHAIN)
    x_in = codes[sl] * VREF / 256
    x_out = vd["v(vout)"][np.searchsorted(td, (np.arange(N_CHAIN) + 0.5) / FS)][sl]
    a = {k: (tone_amplitude(s, F_SIG, FS), tone_amplitude(s, F_INT, FS))
         for k, s in (("in", x_in), ("out", x_out))}
    yf = y[sl] / 32768.0
    rej_fir = 20 * np.log10(tone_amplitude(yf, F_INT, FS) / tone_amplitude(yf, F_SIG, FS)
                            / (a["in"][1] / a["in"][0]))
    gain_sig = 20 * np.log10(a["out"][0] / a["in"][0])
    rej = 20 * np.log10(a["out"][1] / a["in"][1]) - gain_sig
    ok = abs(gain_sig) < 1.0 and rej < -30
    report("chain", ok, f"{N_CHAIN} samples through ADC -> fir.v -> DAC: "
           f"1 kHz tone {gain_sig:+.2f} dB, 15 kHz interferer {rej:.1f} dB relative "
           f"({rej_fir:.1f} dB at the FIR output)")
    return dict(t=t, vin=v["v(vin2)"], codes=codes, y=y, dac_codes=dac_codes,
                td=td, vdac=vd["v(vdac)"], vout=vd["v(vout)"], amps=a,
                gain=gain_sig, rej=rej, rej_fir=rej_fir)


# ---------------------------------------------------------------------------
# Figures for the docs
# ---------------------------------------------------------------------------
def plot(d, a, c):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 11, "axes.spines.top": False,
                         "axes.spines.right": False, "axes.grid": True,
                         "grid.alpha": 0.3, "savefig.dpi": 150, "savefig.bbox": "tight"})
    blue, orange, grey, green = "#0f6e8c", "#e07a1f", "#5b6770", "#2e8b57"
    os.makedirs(IMAGES, exist_ok=True)

    def save(fig, name):
        fig.savefig(os.path.join(IMAGES, name))
        plt.close(fig)
        print("wrote", os.path.relpath(os.path.join(IMAGES, name), REPO))

    # DAC: transfer curve, DNL and INL, ideal vs 1 % mismatch
    fig, ax = plt.subplots(1, 3, figsize=(14, 3.8))
    k = np.arange(256)
    ax[0].step(k, d["v"], where="post", color=blue)
    ax[0].set(title="R-2R DAC output (ngspice)", xlabel="input code", ylabel="vdac (V)")
    ax[1].plot(k[:-1], d["dnl_m"], color=orange, label="1 % resistor mismatch")
    ax[1].plot(k[:-1], d["dnl"], color=blue, label="ideal resistors")
    ax[1].set(title="DNL: error in each step", xlabel="code", ylabel="LSB")
    ax[1].legend(fontsize=9)
    ax[2].plot(k, d["inl_m"], color=orange)
    ax[2].plot(k, d["inl"], color=blue)
    ax[2].set(title="INL: distance from a straight line", xlabel="code", ylabel="LSB")
    save(fig, "analog_dac.png")

    # ADC: ramp in, staircase out
    fig, ax = plt.subplots(1, 2, figsize=(12, 3.8))
    lsb = VREF / 8
    ax[0].step(a["vs"], a["code"], where="post", color=blue, lw=2, label="ADC code (ngspice)")
    ax[0].plot([0, VREF], [0, 8], "--", color=grey, label="vin / LSB")
    for kk in range(1, 8):
        ax[0].axvline((kk - 0.5) * lsb, color=grey, lw=0.5, alpha=0.5)
    ax[0].set(title="3-bit flash ADC: transfer curve", xlabel="sampled vin (V)",
              ylabel="output code", xlim=(-0.1, VREF + 0.1))
    ax[0].legend(fontsize=9)
    err = (a["code"] * lsb - a["vs"]) / lsb
    ax[1].plot(a["vs"], err, ".", color=orange)
    ax[1].axhline(0.5, color=grey, lw=0.8, ls="--")
    ax[1].axhline(-0.5, color=grey, lw=0.8, ls="--")
    ax[1].annotate("overload: above 6.5 LSB\nthe top code saturates", (1.68, -0.8),
                   xytext=(1.05, -1.35), arrowprops=dict(arrowstyle="->", color=grey), fontsize=9)
    ax[1].set(title="quantisation error: within ±½ LSB until full scale", xlabel="sampled vin (V)",
              ylabel="code - vin/LSB", xlim=(0, VREF), ylim=(-1.6, 1.6))
    save(fig, "analog_adc3.png")

    # The chain in the time domain
    ms = 1e3
    n = np.arange(N_CHAIN)
    fig, ax = plt.subplots(4, 1, figsize=(12, 9.5), sharex=True)
    ax[0].plot(c["t"] * ms, c["vin"], color=grey)
    ax[0].set(title="1. analog input: 1 kHz signal + 15 kHz interferer", ylabel="V")
    ax[1].step(n / FS * ms, c["codes"], where="post", color=blue)
    ax[1].set(title="2. 8-bit flash ADC output, 48 kS/s (ngspice)", ylabel="code")
    ax[2].step(n / FS * ms, c["y"] / 32768, where="post", color=green)
    ax[2].set(title="3. after designs/fir/rtl/fir.v (Icarus Verilog), Q1.15", ylabel="value")
    ax[3].step(n / FS * ms, c["dac_codes"] * VREF / 256, where="post", color=orange,
               alpha=0.6, label="vdac: R-2R output (staircase)")
    ax[3].plot(c["td"] * ms, c["vout"], color=blue, lw=2, label="vout: after reconstruction filter")
    ax[3].set(title="4. 8-bit R-2R DAC and reconstruction filter (ngspice)",
              ylabel="V", xlabel="time (ms)")
    ax[3].legend(fontsize=9, loc="upper right")
    fig.tight_layout()
    save(fig, "analog_chain.png")

    # Spectra before and after
    sl = slice(N_CHAIN - 192, N_CHAIN)
    win = np.hanning(192)

    def spec(x):
        s = np.abs(np.fft.rfft((x - np.mean(x)) * win)) / np.sum(win) * 2
        return np.fft.rfftfreq(192, 1 / FS), 20 * np.log10(np.maximum(s, 1e-6))
    x_in = c["codes"][sl] * VREF / 256
    x_out = c["vout"][np.searchsorted(c["td"], (n + 0.5) / FS)][sl]
    fig, ax = plt.subplots(figsize=(10, 3.8))
    f, s = spec(x_in)
    ax.plot(f / 1e3, s, color=grey, label="ADC output (before the FIR)")
    f, s = spec(x_out)
    ax.plot(f / 1e3, s, color=blue, lw=2, label="analog output (after FIR, DAC, filter)")
    ax.annotate(f"interferer {c['rej']:.0f} dB", (F_INT / 1e3, s[np.argmin(abs(f - F_INT))]),
                xytext=(17, -20), arrowprops=dict(arrowstyle="->", color=orange), color=orange)
    ax.set(title="Spectrum: the FIR removes the 15 kHz tone", xlabel="frequency (kHz)",
           ylabel="dBV", ylim=(-90, 0), xlim=(0, FS / 2e3))
    ax.legend(fontsize=9)
    save(fig, "analog_spectrum.png")

    # The same chain as a 3D waterfall: one ribbon per stage
    from matplotlib.collections import PolyCollection
    fig = plt.figure(figsize=(12, 6))
    ax = fig.add_subplot(projection="3d")
    tt = n / FS * ms
    stages = [
        ("analog in", c["t"][::20] * ms, (c["vin"][::20] - VREF / 2) / VREF * 2, grey),
        ("ADC codes", np.repeat(tt, 2)[1:], np.repeat((c["codes"] - 128) / 128, 2)[:-1], blue),
        ("fir.v output", np.repeat(tt, 2)[1:], np.repeat(c["y"] / 32768, 2)[:-1], green),
        ("analog out", c["td"][::20] * ms, (c["vout"][::20] - VREF / 2) / VREF * 2, orange),
    ]
    for i, (lab, x, z, col) in enumerate(stages):
        y = np.full_like(x, i * 1.0)
        ax.plot(x, y, z, color=col, lw=1.6)
        verts = [list(zip(np.r_[x[0], x, x[-1]], np.r_[-1, z, -1]))]
        ax.add_collection3d(PolyCollection(verts, facecolors=col, alpha=0.12), zs=i, zdir="y")
    ax.set_yticks(range(len(stages)))
    ax.set_yticklabels([s_[0] for s_ in stages])
    ax.set_xlabel("time (ms)")
    ax.set_zticks([])
    ax.set_zlim(-1, 1)
    ax.view_init(elev=26, azim=-58)
    ax.set_box_aspect((3.2, 1.9, 0.75), zoom=1.45)
    for axis in (ax.xaxis, ax.yaxis, ax.zaxis):
        axis.pane.set_alpha(0.0)
    fig.subplots_adjust(left=0, right=1, top=1, bottom=0)
    ax.set_title("A real signal through the chip: analog in, ADC, FIR (Verilog), DAC, analog out")
    save(fig, "analog_chain_3d.png")


def schematics():
    """Export the schematics as PNG (light colours) for the docs; needs xvfb-run."""
    for name in ["dac_r2r8", "adc_flash3"]:
        out = os.path.join(IMAGES, f"analog_{name}_sch.png")
        run(["xvfb-run", "-a", "-s", "-screen 0 2400x1400x24", "xschem", "--rcfile",
             os.path.join(HERE, "xschemrc"), "-q", "--preinit", "set dark_colorscheme 0", "--command",
             f"xschem zoom_full; xschem print png {out} 2400 1200; "
             "xschem exit closewindow force", os.path.join(HERE, "sch", f"{name}.sch")],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=120)
        from PIL import Image, ImageChops   # trim the empty margins
        im = Image.open(out).convert("RGB")
        box = ImageChops.difference(im, Image.new("RGB", im.size, "white")).getbbox()
        im.crop((max(box[0] - 20, 0), max(box[1] - 20, 0), min(box[2] + 20, im.width),
                 min(box[3] + 20, im.height))).save(out)
        print("wrote", os.path.relpath(out, REPO))


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "schematics":
        schematics()
        return
    netlist()
    if cmd == "netlist":
        return
    d = dac() if cmd in ("dac", "check", "plot") else None
    a = adc() if cmd in ("adc", "check", "plot") else None
    c = chain() if cmd in ("chain", "check", "plot") else None
    if cmd == "plot":
        plot(d, a, c)
    if not all(results):
        sys.exit(1)
    print(f"PASS: all {len(results)} analog tests")


if __name__ == "__main__":
    main()
